#!/bin/bash
# 批量运行所有测试场景

echo "======================================================================"
echo "开始运行所有测试场景"
echo "======================================================================"

# 定义场景列表
scenarios=(
    "toronto_single"
    "toronto_constellation"
    "shanghai_single"
    "shanghai_constellation"
)

# 运行所有场景
for scenario in "${scenarios[@]}"; do
    echo ""
    echo "----------------------------------------------------------------------"
    echo "正在运行场景: $scenario"
    echo "----------------------------------------------------------------------"
    python run_test.py --scenario "$scenario"
    
    if [ $? -eq 0 ]; then
        echo "✓ 场景 $scenario 运行成功"
    else
        echo "✗ 场景 $scenario 运行失败"
    fi
done

echo ""
echo "======================================================================"
echo "所有场景运行完成"
echo "======================================================================"
